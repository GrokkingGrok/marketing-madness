import { createHash } from 'node:crypto';
import { existsSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import type { Plugin } from 'vite';

function walk(dir: string, base = dir): string[] {
  const files: string[] = [];
  for (const entry of readdirSync(dir)) {
    if (entry === 'sw.js') continue;
    const abs = join(dir, entry);
    if (statSync(abs).isDirectory()) files.push(...walk(abs, base));
    else if (!entry.endsWith('.map')) files.push(relative(base, abs).split(sep).join('/'));
  }
  return files;
}

export function serviceWorkerPlugin(): Plugin {
  return {
    name: 'marketing-madness-sw',
    apply: 'build',
    closeBundle() {
      const dist = join(process.cwd(), 'dist');
      if (!existsSync(dist)) return;
      const files = walk(dist).sort();
      const hash = createHash('sha256').update(files.join('\n')).digest('hex').slice(0, 10);
      const source = `/* Generated by the Marketing Madness build. */
const CACHE = ${JSON.stringify(`marketing-madness-${hash}`)};
const FILES = ${JSON.stringify(files)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(FILES.map((file) => new URL(file, self.location).href)))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    event.respondWith(
      fetch(request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy)).catch(() => {});
          return response;
        })
        .catch(async () => (await caches.match(request)) || (await caches.match(new URL('index.html', self.location).href)) || Response.error())
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy)).catch(() => {});
        }
        return response;
      });
    })
  );
});
`;
      writeFileSync(join(dist, 'sw.js'), source);
    },
  };
}
